// Small hand-written inline SVG icons (Feather-style: 24x24, stroke-based) so the UI
// doesn't need an icon-library dependency (avoids another npm install round trip /
// version-pin risk). Each accepts a `size` and passes through any other prop
// (className, etc.) to the <svg>.

function Svg({ size = 18, children, ...props }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      {...props}
    >
      {children}
    </svg>
  );
}

